# Function to display a student's result
def student_result(name, score):
    print(f"{name} scored {score} marks.")

# Function to check laboratory equipment
def equipment_status(equipment):
    print(f"{equipment} is available in the laboratory.")

# Function to calculate average score
def calculate_average(score1, score2, score3):
    average = (score1 + score2 + score3) / 3
    print("Average Score =", average)

# Function to display attendance
def attendance(total_students):
    print("Total Students Present =", total_students)